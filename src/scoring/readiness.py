"""Resume Readiness Score — transparent, documented, mostly deterministic.

Components (max points):
  parsing     Parsing & document structure            25
  relevance   Job relevance supported by evidence     30  (unavailable without a job description)
  complete    Completeness & consistency              20
  clarity     Clarity & language                      15
  layout      Layout & readability                    10  (available after files are generated)

Every component starts at its maximum and loses points only for specific,
explained findings. Nothing is awarded for being generated by this app.
"""
from __future__ import annotations

import re
from collections import Counter

from pydantic import BaseModel, Field

from src.config import READINESS_NOTE
from src.models.corrections import Correction
from src.models.job import JobAnalysis, RequirementMatch
from src.models.profile import CandidateProfile
from src.models.resume import ResumeDocument
from src.services.correction import PAST_VALUES, VERB_PAST
from src.services.dates import parse_date
from src.services.text_utils import first_word
from src.templates.registry import SECTION_TITLES, TemplateSpec

STANDARD_HEADINGS = {t.lower() for t in SECTION_TITLES.values()} | {
    "summary", "profile", "professional profile", "executive profile", "research profile", "experience",
    "work experience", "employment history", "academic & professional appointments", "core competencies",
    "technical skills", "key competencies", "clinical skills", "transferable skills", "technical toolkit",
    "geospatial & technical skills", "licences & certifications", "professional qualifications",
    "research projects", "relevant projects", "grants & awards", "references", "volunteer experience"}
WEAK_STARTS = ("responsible for", "worked on", "helped with", "duties included", "tasked with", "involved in",
               "in charge of", "assisted with", "participated in")
PRONOUN_RE = re.compile(r"\b(I|me|my|mine|we|our)\b")
ACTION_VERBS = set(VERB_PAST) | PAST_VALUES | {
    "spearheaded", "drove", "owned", "executed", "generated", "achieved", "resolved", "identified", "translated",
    "documented", "configured", "engineered", "architected", "contributed", "partnered", "collaborated",
    "facilitated", "won", "secured", "cut", "grew", "boosted", "accelerated", "championed", "pioneered",
    "redesigned", "restructured", "standardised", "standardized", "consolidated", "authored", "co-authored",
    "published", "analysed", "lectured", "advised", "counselled", "administered", "triaged", "assessed",
    "delivered", "prepared", "built", "led", "ran", "taught", "wrote", "oversaw", "sold", "closed", "negotiated"}


class Deduction(BaseModel):
    points: float
    reason: str
    fix: str = ""


class Component(BaseModel):
    key: str
    name: str
    max_points: int
    points: float | None = None
    available: bool = True
    estimate: bool = False
    deductions: list[Deduction] = Field(default_factory=list)
    passed: list[str] = Field(default_factory=list)
    note: str = ""


class ReadinessReport(BaseModel):
    components: list[Component] = Field(default_factory=list)
    total: float = 0
    max_available: int = 0
    final: bool = False
    note: str = READINESS_NOTE

    @property
    def percent(self) -> int:
        return int(round(100 * self.total / self.max_available)) if self.max_available else 0


def _finish(c: Component) -> Component:
    if c.available:
        lost = sum(d.points for d in c.deductions)
        c.points = round(max(0.0, c.max_points - lost), 1)
    return c


def _capped(c: Component, items: list[tuple[str, str]], each: float, cap: float) -> None:
    lost = 0.0
    for reason, fix in items:
        if lost + each > cap + 1e-9:
            c.deductions.append(Deduction(points=round(cap - lost, 2), reason=f"…and {len(items)} similar issue(s) in total", fix=fix)) if cap - lost > 0 else None
            break
        c.deductions.append(Deduction(points=each, reason=reason, fix=fix))
        lost += each


def _bullets(doc: ResumeDocument) -> list[str]:
    return [b for s in doc.enabled_sections() if s.key in ("experience", "projects", "volunteering")
            for e in s.entries for b in e.bullets]


def score_parsing(doc: ResumeDocument, p: CandidateProfile, template: TemplateSpec, export: dict | None,
                  ats_variant: bool) -> Component:
    c = Component(key="parsing", name="Parsing & document structure", max_points=25)
    if template.presentation_oriented and not ats_variant:
        c.deductions.append(Deduction(points=8, reason=f"'{template.name}' uses a two-column/decorative layout that "
                                      "some ATS read out of order.", fix="Use the parsing-friendly export for online portals."))
    else:
        c.passed.append("Single-column, text-based layout")
    odd = [s.title for s in doc.enabled_sections() if s.title.lower() not in STANDARD_HEADINGS]
    _capped(c, [(f"Non-standard heading '{t}'", "Use a conventional heading such as 'Experience' or 'Skills'.") for t in odd], 1, 3)
    if not odd:
        c.passed.append("Conventional section headings")
    if not p.contact.email:
        c.deductions.append(Deduction(points=3, reason="No email address in the document.", fix="Add an email address."))
    elif not p.contact.phone:
        c.deductions.append(Deduction(points=1, reason="No phone number.", fix="Add a phone number if you are comfortable doing so."))
    else:
        c.passed.append("Contact details in the document body (not a header/footer)")
    bad_dates = [f"{e.title}: '{e.start_date or e.end_date}'" for e in p.experience
                 if (e.start_date and not parse_date(e.start_date)) or (e.end_date and not e.current and not parse_date(e.end_date))]
    _capped(c, [(f"Unrecognised date format ({d})", "Use formats like 'Mar 2021' or '2021'.") for d in bad_dates], 1, 3)
    if export:
        pdf = export.get("pdf", {})
        if pdf.get("text_extractable") is False:
            c.deductions.append(Deduction(points=12, reason="PDF text could not be extracted.", fix="Regenerate the document."))
        else:
            c.passed.append("PDF text is selectable and extractable")
        if pdf.get("reading_order") is False:
            c.deductions.append(Deduction(points=3, reason="Extracted reading order differs from the visual order.",
                                          fix="Use a single-column template or the parsing-friendly export."))
        missing = pdf.get("missing_text", [])
        if missing:
            c.deductions.append(Deduction(points=min(5, len(missing)), reason=f"{len(missing)} expected item(s) not found in extracted PDF text.",
                                          fix="Review the Validate step for details."))
    else:
        c.note = "Provisional until the files are generated and re-opened for validation."
    return _finish(c)


def score_relevance(matches: list[RequirementMatch], analysis: JobAnalysis | None, jd: str) -> Component:
    c = Component(key="relevance", name="Job relevance supported by evidence", max_points=30)
    if not jd.strip() or not analysis or not analysis.requirements:
        c.available = False
        c.note = "Unavailable — add a job description to assess relevance. No job-specific score is calculated."
        return c
    weights = {m.requirement_id: (2.0 if m.importance == "required" else 1.0) for m in matches}
    total_w = sum(weights.values()) or 1.0
    for m in matches:
        lost = 30 * weights[m.requirement_id] / total_w * (1 - m.strength)
        if lost > 0.05:
            fix = {"not_demonstrated": "Only add this if you genuinely have the experience; otherwise address it in a cover letter.",
                   "transferable": "Explain the transferable experience in a bullet, using your real example.",
                   "needs_clarification": "Confirm or add a specific example in your profile.",
                   "supported": "Show it in a role or project bullet rather than only the skills list."}[m.status]
            if m.status == "supported" and m.note:
                fix = m.note
            c.deductions.append(Deduction(points=round(lost, 1), reason=f"{m.importance.title()}: {m.requirement[:110]} — {m.status.replace('_', ' ')}", fix=fix))
        else:
            c.passed.append(f"Supported: {m.requirement[:80]}")
    c.estimate = any(m.method == "llm-estimate" for m in matches)
    c.note = ("Includes AI-assisted relevance judgements — treat as an estimate." if c.estimate
              else "Rule-based keyword and evidence matching against the supplied job description.")
    return _finish(c)


def score_completeness(p: CandidateProfile, validation: dict | None) -> Component:
    c = Component(key="complete", name="Completeness & consistency", max_points=20)
    d = c.deductions.append
    if not p.summary and "summary" not in p.skipped_fields:
        c.note = "A factual summary is drafted from your data when you don't supply one."
    if not p.experience and p.career_stage not in ("graduate",) and not p.projects:
        d(Deduction(points=4, reason="No work experience or projects.", fix="Add roles, internships, projects or volunteering."))
    no_bullets = [e.title or "untitled role" for e in p.experience if not e.bullets]
    _capped(c, [(f"'{t}' has no achievements listed", "Add 2–5 points describing what you did.") for t in no_bullets], 2, 4)
    no_dates = [e.title for e in p.experience if not e.start_date]
    _capped(c, [(f"'{t}' has no dates", "Add start and end dates.") for t in no_dates], 1, 3)
    if not p.education:
        d(Deduction(points=4, reason="No education listed.", fix="Add your highest qualification."))
    if not p.skills.technical:
        d(Deduction(points=4, reason="No technical skills listed.", fix="List the tools and skills you actually use."))
    words = sum(len(b.split()) for e in p.experience for b in e.bullets) + \
        sum(len((pr.description + " " + " ".join(pr.bullets)).split()) for pr in p.projects)
    if (p.experience or p.projects) and words < 40:
        d(Deduction(points=3, reason=f"Very little detail about your work ({words} words across all points).",
                    fix="Describe what you did, the tools you used and real outcomes for each role."))
    if validation:
        blocking = [i for i in validation.get("issues", []) if i.get("blocking")]
        _capped(c, [(i["message"], "Resolve it in the Review step.") for i in blocking], 3, 6)
        warns = [i for i in validation.get("issues", []) if i.get("severity") == "warning" and not i.get("blocking")
                 and "achievements" not in i["message"] and "no dates" not in i["message"]]
        _capped(c, [(i["message"], "Review and confirm.") for i in warns], 1, 3)
    if not c.deductions:
        c.passed.append("All core sections present and consistent")
    return _finish(c)


def score_clarity(doc: ResumeDocument, pending: list[Correction]) -> Component:
    c = Component(key="clarity", name="Clarity & language", max_points=15)
    bullets = _bullets(doc)
    weak = [b for b in bullets if b.lower().startswith(WEAK_STARTS)]
    _capped(c, [(f"Weak opening: “{b[:60]}…”", "Start with a specific action verb (e.g. 'Managed', 'Built').") for b in weak], 1, 4)
    pron = [b for b in bullets if PRONOUN_RE.search(b)]
    summary = next((s.text for s in doc.enabled_sections() if s.key == "summary"), "")
    if PRONOUN_RE.search(summary):
        pron.append(summary)
    _capped(c, [(f"Personal pronoun in “{b[:60]}…”", "Remove 'I/my/we' — resume style is implied first person.") for b in pron], 1, 3)
    long_ = [b for b in bullets if len(b.split()) > 35]
    _capped(c, [(f"Long point ({len(b.split())} words): “{b[:50]}…”", "Aim for under 30 words.") for b in long_], 0.5, 2)
    short = [b for b in bullets if len(b.split()) < 4]
    _capped(c, [(f"Very short point: “{b}”", "Add what you did and the context or result.") for b in short], 1, 3)
    firsts = Counter(first_word(b) for b in bullets if first_word(b))
    rep = [w for w, n in firsts.items() if n >= 4]
    if rep:
        c.deductions.append(Deduction(points=1, reason=f"Repeated opening verb(s): {', '.join(rep)}", fix="Vary verbs where accurate."))
    nonverb = [b for b in bullets if first_word(b) and first_word(b) not in ACTION_VERBS and not b.lower().startswith(WEAK_STARTS)]
    if bullets and len(nonverb) / len(bullets) > 0.5:
        c.deductions.append(Deduction(points=1, reason="Most points do not start with an action verb.",
                                      fix="Lead each point with what you did."))
    open_sugg = [x for x in pending if x.status == "pending"]
    _capped(c, [(f"Unconfirmed language suggestion: {x.explanation[:70]}", "Accept or reject it in Review corrections.") for x in open_sugg], 1, 3)
    if len(summary.split()) > 90:
        c.deductions.append(Deduction(points=1, reason="Summary is longer than 90 words.", fix="Keep it to 2–4 sentences."))
    quantified = sum(1 for b in bullets if re.search(r"\d", b))
    if len(bullets) >= 4 and quantified / len(bullets) < 0.25:
        c.deductions.append(Deduction(points=1, reason=f"Only {quantified} of {len(bullets)} points include a measurable detail.",
                                      fix="Add real figures you know (counts, scale, time). Never estimate or invent them."))
    if not c.deductions:
        c.passed.append("Concise, action-led wording")
    return _finish(c)


def score_layout(render: dict | None, export: dict | None, max_pages: int | None) -> Component:
    c = Component(key="layout", name="Layout & readability", max_points=10)
    if not render:
        c.available = False
        c.note = "Calculated after the documents are generated."
        return c
    pages = render.get("pages", 0)
    if max_pages and pages > max_pages:
        c.deductions.append(Deduction(points=4, reason=f"{pages} pages exceeds the {max_pages}-page target.",
                                      fix="Apply the fit suggestions or choose a longer target."))
    else:
        c.passed.append(f"Fits the page target ({pages} page{'s' if pages != 1 else ''})")
    if render.get("body_size", 11) < 10.5:
        c.deductions.append(Deduction(points=1, reason=f"Body text reduced to {render['body_size']} pt to fit.",
                                      fix="Trim lower-priority content to restore 10.5–11 pt."))
    if render.get("density", 0) >= 3:
        c.deductions.append(Deduction(points=1, reason="Tight margins and spacing were needed to fit.",
                                      fix="Trim content for a more balanced page."))
    if export:
        pdf = export.get("pdf", {})
        if pdf.get("blank_pages"):
            c.deductions.append(Deduction(points=3, reason="Blank page detected.", fix="Regenerate after trimming."))
        if pdf.get("clipped"):
            c.deductions.append(Deduction(points=3, reason="Text extends beyond the page edge.", fix="Regenerate; report if it persists."))
        if pdf.get("sparse_last_page"):
            c.deductions.append(Deduction(points=1, reason="The last page holds only a few lines.",
                                          fix="Trim slightly to save a page, or add relevant detail."))
    return _finish(c)


def assess(p: CandidateProfile, doc: ResumeDocument, template: TemplateSpec, matches: list[RequirementMatch],
           analysis: JobAnalysis | None, validation: dict | None, corrections: list[Correction],
           render: dict | None = None, export: dict | None = None, max_pages: int | None = 1,
           ats_variant: bool = False) -> ReadinessReport:
    comps = [score_parsing(doc, p, template, export, ats_variant),
             score_relevance(matches, analysis, p.target.job_description),
             score_completeness(p, validation),
             score_clarity(doc, corrections),
             score_layout(render, export, max_pages)]
    avail = [x for x in comps if x.available]
    return ReadinessReport(components=comps, total=round(sum(x.points or 0 for x in avail), 1),
                           max_available=sum(x.max_points for x in avail), final=bool(render and export))
